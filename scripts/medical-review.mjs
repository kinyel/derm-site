// node scripts/medical-review.mjs — writes docs/MEDICAL_REVIEW.md: every page with medical content, grouped by who
// should review it, with a tick box each. A page counts as reviewed when its content file has `reviewedBy` and
// `reviewedOn` filled in (the page then shows a "Medically reviewed by" line).
import fs from 'node:fs';
import path from 'node:path';
import yaml from 'js-yaml';
import { r } from './lib.mjs';

const dir = (c) => r('src', 'content', c);
const read = (c) =>
  fs
    .readdirSync(dir(c))
    .filter((f) => f.endsWith('.md'))
    .map((f) => {
      const raw = fs.readFileSync(path.join(dir(c), f), 'utf8');
      const fm = yaml.load(raw.split(/^---\s*$/m)[1] ?? '') ?? {};
      return { id: f.replace(/\.md$/, ''), ...fm };
    });
const done = (x) => Boolean(x.reviewedBy && x.reviewedOn);
const services = read('services').sort((a, b) => (a.order ?? 99) - (b.order ?? 99));
const procedures = read('procedures');
const conditions = read('conditions').sort((a, b) => String(a.shortTitle ?? a.title).localeCompare(String(b.shortTitle ?? b.title)));
const articles = read('articles').sort((a, b) => String(a.title).localeCompare(String(b.title)));
const faqs = yaml.load(fs.readFileSync(path.join(dir('faqs'), 'clinic.yaml'), 'utf8')) ?? [];

const im = (id) => id === 'internal-medicine';
const row = (x, name, url) => `- [${done(x) ? 'x' : ' '}] ${name} — \`${url}\``;
const out = [];
const groups = [];
const add = (title, note, rows) => {
  groups.push([title, rows.length, rows.filter((l) => l.startsWith('- [x]')).length]);
  out.push(`## ${title} (${rows.length})`, '', note, '', ...rows, '');
};

const dermServices = services.filter((s) => !im(s.id));
const dermProcs = procedures.filter((p) => !im(p.category));
const imProcs = procedures.filter((p) => im(p.category));
add('Internal medicine: for the physician', 'These are not dermatology. They should be read by the doctor who provides the service.', [
  ...services.filter((s) => im(s.id)).map((s) => row(s, `${s.title} (category page)`, `/services/${s.id}/`)),
  ...imProcs.sort((a, b) => (a.order ?? 99) - (b.order ?? 99)).map((p) => row(p, p.title, `/services/${p.category}/${p.id}/`)),
]);
add('Treatments and procedures: for the dermatologist', 'What each treatment is, who it suits, what to expect, risks and aftercare. Check the devices and products named against what the clinic actually uses.', dermServices.flatMap((s) => dermProcs.filter((p) => p.category === s.id).sort((a, b) => (a.order ?? 99) - (b.order ?? 99)).map((p) => row(p, `${p.title} · ${s.navLabel ?? s.title}`, `/services/${p.category}/${p.id}/`))));
add('Service category pages: for the dermatologist', 'Short overviews of each area of the clinic and the list of what is offered under it.', dermServices.map((s) => row(s, s.title, `/services/${s.id}/`)));
add('Condition guides: for the dermatologist', 'Signs, causes, what to avoid, when to see a doctor, and how the clinic treats it.', conditions.map((c) => row(c, c.shortTitle ?? c.title, `/conditions/${c.id}/`)));
add('Articles: for the dermatologist', 'Longer answers to common questions. Each ends with its sources.', articles.map((a) => row(a, a.title, `/blog/${a.id}/`)));

const medicalFaqs = faqs.filter((f) => !['booking', 'fees-and-hmo'].includes(f.group));
const pages = groups.reduce((n, g) => n + g[1], 0);
const head = [
  '# Medical review checklist',
  '',
  `Generated by \`node scripts/medical-review.mjs\`. **${pages} pages carry medical content and ${groups.reduce((n, g) => n + g[2], 0)} of them have been reviewed.**`,
  '',
  'No clinician has read these pages yet. They were written from published guidance and say nothing the sources do not, but they speak in the clinic\'s name, so the clinic\'s doctors should confirm every one before launch.',
  '',
  'How to mark a page as reviewed: open its content file (or the page in the editor at `/keystatic`), fill in `reviewedBy` (the doctor\'s name and title) and `reviewedOn` (the date). The page then shows "Medically reviewed by …" and this list ticks it on the next run.',
  '',
  '| Group | Pages | Reviewed |',
  '|---|---|---|',
  ...groups.map(([t, n, d]) => `| ${t} | ${n} | ${d} |`),
  `| **Total** | **${pages}** | **${groups.reduce((n, g) => n + g[2], 0)}** |`,
  '',
  '## Also worth the doctor\'s eye (not counted above)',
  '',
  `- The clinic\'s questions and answers at \`/faq/\`: ${medicalFaqs.length} of ${faqs.length} touch on care (the rest are about booking and payment).`,
  '- The home page: the section "Care for every skin type and tone" makes four short medical statements.',
  '- `/your-visit/`: what happens at a consultation and what to bring.',
  '- `/medical-disclaimer/` and `/editorial-policy/`: these describe how the medical content is written and reviewed; the lawyer and the doctor should both read them.',
  '- `/about/lead-dermatologist/`: the profile is waiting for the doctor\'s name, qualifications and memberships (listed as missing facts in `docs/FINAL_REPORT.md`).',
  '',
];
fs.writeFileSync(r('docs', 'MEDICAL_REVIEW.md'), [...head, ...out].join('\n'));
console.log(`docs/MEDICAL_REVIEW.md written: ${pages} pages, ${groups.map(([t, n]) => `${n} ${t.split(':')[0].toLowerCase()}`).join(' · ')}; FAQs touching care: ${medicalFaqs.length}/${faqs.length}`);
console.log(JSON.stringify({ im: imProcs.map((p) => p.title), cats: dermServices.map((s) => s.title), procs: dermServices.map((s) => [s.navLabel ?? s.title, dermProcs.filter((p) => p.category === s.id).sort((a, b) => (a.order ?? 99) - (b.order ?? 99)).map((p) => p.title)]).filter(([, l]) => l.length), conditions: conditions.map((c) => c.shortTitle ?? c.title), articles: articles.map((a) => a.title) }));
