// npm run images:missing — lists registry images that are not on disk yet. Never fails.
import { allImages, groupLabels } from './images-lib.mjs';

const all = allImages();
const missing = all.filter((i) => !i.exists);
const required = missing.filter((i) => !i.optional);
if (process.argv.includes('--md')) {
  // docs/IMAGES_NEEDED.md: every image the site expects, whether it is in place, and where it is used (Addendum A.7).
  const fs = await import('node:fs');
  const { r } = await import('./lib.mjs');
  const ratio = (w, h) => { const g = (a, b) => (b ? g(b, a % b) : a); const d = g(w, h); return `${w / d}:${h / d}`; };
  const rows = all.filter((i) => !i.optional).map((i) => `| \`${i.path}\` | ${i.width}×${i.height} (${ratio(i.width, i.height)}) | ${i.pages.join('; ')} | ${groupLabels[i.group]}${i.realPhotoOnly ? ' (real photograph only)' : ''} | ${i.exists ? 'in place' : '**missing**'} |`);
  const md = [
    '# Images needed',
    '',
    `Generated by \`npm run images:missing -- --md\` (also run at the end of \`npm run images:refresh\`). ${all.filter((i) => i.exists).length} of ${all.length} registry images are in place; ${required.length} required images are missing.`,
    '',
    'Save each file at the path shown, at the size shown or larger with the same aspect ratio, then run `npm run images:refresh`. Until a file arrives the page shows the brand placeholder at the same aspect ratio, so nothing moves when the real image is added. The alt text for every image is already set in `src/data/images.ts`; check it still describes the picture you supply.',
    '',
    '`IMAGE_PROMPTS.md` was not supplied with the brief, so the last-but-one column names the image group from brief §17 instead of a section of that document (see DECISIONS D20).',
    '',
    '| File | Size (ratio) | Where it is used | Group (brief §17) | Status |',
    '|---|---|---|---|---|',
    ...rows,
    '',
    '## Optional condition illustrations',
    '',
    `One per condition page, 1200×1200 (1:1), at \`src/assets/images/illustrations/{condition-slug}.png\`. None is required: a page without one simply shows no illustration. ${all.filter((i) => i.optional && i.exists).length} of ${all.filter((i) => i.optional).length} are in place.`,
    '',
    '## Notes',
    '',
    '- **Hero cut-out** (`hero-cutout.png`): a transparent PNG. Any aspect ratio works; the picture is read at its own ratio. Its left, right and bottom edges fade automatically, so an arm or shoulder that runs off the frame never shows a cut line (DECISIONS D23). The depth map `hero-depth.png` is generated by `npm run images:refresh`.',
    '- **Real photographs only** for staff, premises and equipment. Never generated people or buildings.',
    '- **Logo** (`src/assets/brand/logo.svg`): once present, favicons and app icons are generated from it.',
    '',
  ].join('\n');
  fs.writeFileSync(r('docs/IMAGES_NEEDED.md'), md);
  console.log('docs/IMAGES_NEEDED.md written.');
  process.exit(0);
}
if (process.argv.includes('--json')) {
  console.log(JSON.stringify(missing.map(({ id, path, optional }) => ({ id, path, optional: Boolean(optional) }))));
  process.exit(0);
}
console.log(`\nImages: ${all.length - missing.length} of ${all.length} present. ${required.length} missing, plus ${missing.length - required.length} optional illustrations.\n`);
let group = '';
for (const i of missing.filter((m) => !m.optional)) {
  if (i.group !== group) {
    group = i.group;
    console.log(`  ${groupLabels[group]}`);
  }
  console.log(`    · ${i.path}  (${i.width}×${i.height})`);
}
if (missing.some((m) => m.optional)) console.log(`\n  Optional: ${missing.filter((m) => m.optional).length} condition illustrations in src/assets/images/illustrations/{condition-slug}.png`);
console.log('\nMissing images show the brand placeholder. Add files, then run "npm run images:refresh".\n');
